function normalizeToken(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}

function translateToken(token: string): string {
  const translation = WORD_TRANSLATIONS[normalizeToken(token)]

  if (!translation) {
    return token
  }

  if (/^\p{Lu}/u.test(token)) {
    return translation.charAt(0).toLocaleUpperCase('pt-BR') + translation.slice(1)
  }

  return translation
}

export function translateExerciseName(name: string): string {
  let translatedName = name
  const startsWithCapital = /^\p{Lu}/u.test(name)

  for (const [pattern, translation] of PHRASE_TRANSLATIONS) {
    translatedName = translatedName.replace(pattern, translation)
  }

  translatedName = translatedName
    .replace(/\p{L}[\p{L}\p{M}]*/gu, translateToken)
    .replace(/\s+/g, ' ')
    .trim()

  if (startsWithCapital) {
    translatedName = translatedName.replace(/^\p{Ll}/u, (letter) =>
      letter.toLocaleUpperCase('pt-BR'),
    )
  }

  return translatedName
}